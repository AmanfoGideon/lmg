create or replace function public.create_transaction(
  p_client_id bigint,
  p_client_name text,
  p_amount numeric,
  p_type text,
  p_payment_method text,
  p_description text,
  p_date date,
  p_invoice_id bigint default null
)
returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_client_id bigint := p_client_id;
  v_id bigint;
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_type not in ('income', 'expense', 'invoice', 'payment') then
    raise exception 'Unsupported transaction type' using errcode = '22023';
  end if;
  if p_type = 'payment' and p_invoice_id is not null then
    return public.record_invoice_payment(p_invoice_id, p_amount, p_payment_method, p_description, p_date);
  end if;

  if v_client_id is null then
    if nullif(btrim(p_client_name), '') is null then
      raise exception 'A client is required' using errcode = '22023';
    end if;
    select id into v_client_id from public.clients
    where lower(full_name) = lower(btrim(p_client_name))
    order by id limit 1;
    if v_client_id is null then
      insert into public.clients (full_name) values (btrim(p_client_name)) returning id into v_client_id;
    end if;
  end if;

  insert into public.transactions (client_id, amount, type, payment_method, description, date, invoice_id)
  values (v_client_id, p_amount, p_type, p_payment_method, p_description, coalesce(p_date, current_date), p_invoice_id)
  returning id into v_id;
  insert into public.user_logs (user_id, action, details)
  values ((select auth.uid()), 'transaction_create', v_client_id::text || '|' || p_type || '|' || p_amount::text);
  return v_id;
end;
$$;

create or replace function public.update_transaction(
  p_id bigint,
  p_amount numeric,
  p_type text,
  p_payment_method text,
  p_description text,
  p_date date,
  p_invoice_id bigint default null
)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_type not in ('income', 'expense', 'invoice', 'payment') then
    raise exception 'Unsupported transaction type' using errcode = '22023';
  end if;
  update public.transactions
  set amount = p_amount, type = p_type, payment_method = p_payment_method,
      description = p_description, date = coalesce(p_date, current_date), invoice_id = p_invoice_id
  where id = p_id;
  if not found then
    raise exception 'Transaction not found' using errcode = '22023';
  end if;
  insert into public.user_logs (user_id, action, details)
  values ((select auth.uid()), 'transaction_update', p_id::text || '|' || p_type || '|' || p_amount::text);
end;
$$;

create or replace function public.delete_transaction(p_id bigint)
