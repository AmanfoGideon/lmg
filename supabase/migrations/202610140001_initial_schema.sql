create or replace function public.claim_sms_messages(p_batch_size integer default 100, p_max_retry integer default 3)
returns setof public.sms_messages
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_batch_size < 1 or p_batch_size > 200 or p_max_retry < 0 or p_max_retry > 10 then
    raise exception 'Invalid SMS dispatch limits' using errcode = '22023';
  end if;

  return query
  with candidates as (
    select id
    from public.sms_messages
    where (
      status = 'queued'
      and (scheduled_for is null or scheduled_for <= now())
    ) or (
      status = 'failed'
      and retry_count < p_max_retry
      and (next_retry_at is null or next_retry_at <= now())
      and (scheduled_for is null or scheduled_for <= now())
    ) or (
      status = 'sending'
      and retry_count < p_max_retry
      and last_attempt_at <= now() - interval '15 minutes'
      and (scheduled_for is null or scheduled_for <= now())
    )
    order by coalesce(next_retry_at, scheduled_for, created_at), id
    limit p_batch_size
    for update skip locked
  )
  update public.sms_messages as message
  set status = 'sending',
      retry_count = case when message.status in ('failed', 'sending') then message.retry_count + 1 else message.retry_count end,
      last_attempt_at = now(),
      next_retry_at = null
  from candidates
  where message.id = candidates.id
  returning message.*;
end;
$$;

revoke all on function public.claim_sms_messages(integer, integer) from public, anon, authenticated;
grant execute on function public.claim_sms_messages(integer, integer) to service_role;

