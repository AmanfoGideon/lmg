create or replace function public.recalculate_invoice_payment_status(p_invoice_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_total numeric(10, 2);
  v_paid numeric(10, 2);
  v_status text;
begin
  select total into v_total from public.invoices where id = p_invoice_id for update;
  if not found then
    return;
  end if;

  select coalesce(sum(amount), 0) into v_paid
  from public.transactions
  where invoice_id = p_invoice_id and type = 'payment';

  v_status := case
    when v_paid <= 0 then 'unpaid'
    when v_paid < coalesce(v_total, 0) then 'partial'
    else 'paid'
  end;

  update public.invoices set status = v_status where id = p_invoice_id;
end;
$$;

create or replace function public.sync_invoice_payment_status()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'DELETE' then
    if old.invoice_id is not null and old.type = 'payment' then
      perform public.recalculate_invoice_payment_status(old.invoice_id);
    end if;
    return null;
  elsif tg_op = 'UPDATE' then
    if old.invoice_id is not null and old.type = 'payment' then
      perform public.recalculate_invoice_payment_status(old.invoice_id);
    end if;
    if new.invoice_id is not null and new.type = 'payment' then
      perform public.recalculate_invoice_payment_status(new.invoice_id);
    end if;
    return null;
  elsif tg_op = 'INSERT' then
    if new.invoice_id is not null and new.type = 'payment' then
      perform public.recalculate_invoice_payment_status(new.invoice_id);
    end if;
  end if;
  return null;
end;
$$;

