create or replace function public.reset_business_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_table text;
  v_sequence text;
  v_max_id bigint;
begin
  foreach v_table in array array[
    'clients', 'invoices', 'products', 'invoice_items', 'transactions',
    'client_interactions', 'user_logs', 'sms_messages'
  ] loop
    v_sequence := pg_get_serial_sequence(format('public.%I', v_table), 'id');
    if v_sequence is not null then
      execute format('select coalesce(max(id), 0) from public.%I', v_table) into v_max_id;
      perform setval(v_sequence::regclass, greatest(v_max_id, 1), v_max_id > 0);
    end if;
  end loop;
end;
$$;

revoke all on function public.reset_business_identity_sequences() from public, anon, authenticated;
grant execute on function public.reset_business_identity_sequences() to service_role;
