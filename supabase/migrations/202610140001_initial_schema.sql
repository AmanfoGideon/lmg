create or replace function public.import_clients(p_rows jsonb)
returns table (inserted_count integer, updated_count integer)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_row jsonb;
  v_name text;
  v_phone text;
  v_email text;
  v_address text;
  v_client_id bigint;
  v_inserted integer := 0;
  v_updated integer := 0;
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) > 5000 then
    raise exception 'Client import must contain no more than 5000 rows' using errcode = '22023';
  end if;
  perform set_config('lmg.skip_client_audit', 'on', true);

  for v_row in select value from jsonb_array_elements(p_rows)
  loop
    v_name := nullif(btrim(v_row ->> 'full_name'), '');
    v_phone := nullif(btrim(v_row ->> 'phone'), '');
    v_email := nullif(btrim(v_row ->> 'email'), '');
    v_address := nullif(btrim(v_row ->> 'address'), '');
    if v_name is null and v_email is null and v_phone is null then
      continue;
    end if;
    if v_name is null then
      v_name := coalesce(v_email, v_phone);
    end if;

    v_client_id := null;
    if v_email is not null then
      select id into v_client_id from public.clients
      where lower(email) = lower(v_email) order by id limit 1 for update;
    end if;
    if v_client_id is null and v_phone is not null then
      select id into v_client_id from public.clients
      where phone = v_phone order by id limit 1 for update;
    end if;
    if v_client_id is null then
      select id into v_client_id from public.clients
      where lower(full_name) = lower(v_name) order by id limit 1 for update;
    end if;

    if v_client_id is null then
      insert into public.clients (full_name, phone, email, address)
      values (v_name, v_phone, v_email, v_address);
      v_inserted := v_inserted + 1;
    else
      update public.clients
      set full_name = coalesce(v_name, full_name),
          phone = coalesce(v_phone, phone),
          email = coalesce(v_email, email),
          address = coalesce(v_address, address)
      where id = v_client_id;
      v_updated := v_updated + 1;
    end if;
  end loop;

  insert into public.user_logs (user_id, action, details)
  values ((select auth.uid()), 'clients_import_csv', v_inserted::text || '|' || v_updated::text);
  return query select v_inserted, v_updated;
end;
$$;

revoke all on function public.import_clients(jsonb) from public, anon;
grant execute on function public.import_clients(jsonb) to authenticated;

