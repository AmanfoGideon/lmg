create or replace function public.audit_business_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := auth.uid();
  v_id bigint;
  v_action text;
  v_details text;
begin
  if v_actor is null or current_setting('lmg.skip_client_audit', true) = 'on' then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    v_id := old.id;
    if tg_table_name = 'clients' then v_details := old.full_name; end if;
    if tg_table_name = 'products' then v_details := old.name; end if;
  else
    v_id := new.id;
    if tg_table_name = 'clients' then v_details := new.full_name; end if;
    if tg_table_name = 'products' then v_details := new.name; end if;
  end if;

  if tg_table_name = 'clients' then
    v_action := case tg_op when 'INSERT' then 'client_create' when 'UPDATE' then 'client_update' else 'client_delete' end;
  elsif tg_table_name = 'products' then
    v_action := case tg_op when 'INSERT' then 'product_create' when 'UPDATE' then 'product_update' else 'product_delete' end;
  elsif tg_table_name = 'client_interactions' then
    v_action := 'client_note';
    v_details := coalesce(new.client_id, old.client_id)::text;
  elsif tg_table_name = 'invoices' then
    v_action := 'invoice_status';
    v_details := coalesce(new.id, old.id)::text || '|' || coalesce(new.status, old.status);
  end if;

  if v_action is not null then
    insert into public.user_logs (user_id, action, details)
    values (v_actor, v_action, coalesce(v_details, v_id::text));
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.audit_business_change() from public, anon, authenticated;

create trigger clients_audit_change
