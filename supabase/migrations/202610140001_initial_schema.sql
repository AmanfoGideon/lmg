    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_period not in ('week', 'month', 'year') then
    raise exception 'Unsupported dashboard period' using errcode = '22023';
  end if;

  if p_period = 'week' then
    v_start := current_date - 6;
  elsif p_period = 'year' then
    v_start := make_date(extract(year from current_date)::integer, 1, 1);
  else
    v_start := date_trunc('month', current_date)::date;
  end if;

  select
    coalesce(sum(case when type in ('income', 'payment') then amount else 0 end), 0),
    coalesce(sum(case when type = 'expense' then amount else 0 end), 0)
  into v_income, v_expense
  from public.transactions
  where date between v_start and v_end;

  select
    coalesce(sum(case when type in ('income', 'payment') then amount else 0 end), 0),
    coalesce(sum(case when type = 'expense' then amount else 0 end), 0),
    count(*)
  into v_week_income, v_week_expense, v_week_count
  from public.transactions
  where date between current_date - 6 and current_date;

  select
    coalesce(jsonb_agg(to_char(day_date, 'Dy') order by day_date), '[]'::jsonb),
    coalesce(jsonb_agg(income_total order by day_date), '[]'::jsonb),
    coalesce(jsonb_agg(expense_total order by day_date), '[]'::jsonb),
    coalesce(jsonb_agg(income_total - expense_total order by day_date), '[]'::jsonb)
  into v_week_labels, v_week_income_series, v_week_expense_series, v_week_trend
  from (
    select days.day_date::date as day_date,
      coalesce(sum(case when t.type in ('income', 'payment') then t.amount else 0 end), 0) as income_total,
      coalesce(sum(case when t.type = 'expense' then t.amount else 0 end), 0) as expense_total
    from generate_series(current_date - 6, current_date, interval '1 day') as days(day_date)
    left join public.transactions as t on t.date = days.day_date::date
    group by days.day_date::date
  ) as daily;

  if p_period = 'week' then
    v_chart_labels := v_week_labels;
    v_chart_income := v_week_income_series;
    v_chart_expense := v_week_expense_series;
  elsif p_period = 'year' then
    select
      coalesce(jsonb_agg(to_char(month_start, 'Mon') order by month_start), '[]'::jsonb),
      coalesce(jsonb_agg(income_total order by month_start), '[]'::jsonb),
      coalesce(jsonb_agg(expense_total order by month_start), '[]'::jsonb)
    into v_chart_labels, v_chart_income, v_chart_expense
    from (
      select months.month_start::date as month_start,
        coalesce(sum(case when t.type in ('income', 'payment') then t.amount else 0 end), 0) as income_total,
        coalesce(sum(case when t.type = 'expense' then t.amount else 0 end), 0) as expense_total
      from generate_series(date_trunc('year', current_date), date_trunc('year', current_date) + interval '11 months', interval '1 month') as months(month_start)
      left join public.transactions as t
        on t.date >= months.month_start::date and t.date < (months.month_start + interval '1 month')::date
      group by months.month_start::date
    ) as monthly;
  else
    select
      coalesce(jsonb_agg(to_char(month_start, 'Mon') order by month_start), '[]'::jsonb),
      coalesce(jsonb_agg(income_total order by month_start), '[]'::jsonb),
      coalesce(jsonb_agg(expense_total order by month_start), '[]'::jsonb)
    into v_chart_labels, v_chart_income, v_chart_expense
    from (
      select months.month_start::date as month_start,
        coalesce(sum(case when t.type in ('income', 'payment') then t.amount else 0 end), 0) as income_total,
        coalesce(sum(case when t.type = 'expense' then t.amount else 0 end), 0) as expense_total
      from generate_series(date_trunc('month', current_date) - interval '11 months', date_trunc('month', current_date), interval '1 month') as months(month_start)
      left join public.transactions as t
        on t.date >= months.month_start::date and t.date < (months.month_start + interval '1 month')::date
      group by months.month_start::date
    ) as monthly;
  end if;

  select jsonb_build_object(
    'month', jsonb_build_object(
      'income', v_income,
      'expense', v_expense,
      'profit', v_income - v_expense,
      'pending_invoices', (select count(*) from public.invoices where status <> 'paid')
    ),
    'weekly', jsonb_build_object(
      'income', v_week_income,
      'expense', v_week_expense,
      'profit', v_week_income - v_week_expense,
      'count', v_week_count
    ),
    'weeklyLabels', v_week_labels,
    'weeklyIncome', v_week_income_series,
    'weeklyExpense', v_week_expense_series,
    'weeklyTrend', v_week_trend,
    'monthlyChart', jsonb_build_object(
      'labels', v_chart_labels,
      'income', v_chart_income,
      'expense', v_chart_expense
    ),
    'recent', coalesce((
      select jsonb_agg(to_jsonb(recent_rows) order by recent_rows.date desc, recent_rows.id desc)
      from (
        select t.id, t.type, t.amount, t.date, c.full_name as client
        from public.transactions as t
        left join public.clients as c on c.id = t.client_id
        where t.date between v_start and v_end
        order by t.date desc, t.id desc
        limit 25
      ) as recent_rows
    ), '[]'::jsonb),
    'topClients', coalesce((
      select jsonb_agg(to_jsonb(client_rows) order by client_rows.total desc)
      from (
        select c.full_name as name, coalesce(sum(t.amount), 0) as total
        from public.clients as c
        left join public.transactions as t
          on t.client_id = c.id and t.type in ('income', 'payment') and t.date between v_start and v_end
        group by c.id
        order by total desc
        limit 5
      ) as client_rows
    ), '[]'::jsonb),
    'inventory', jsonb_build_object(
      'low_stock', (select count(*) from public.products where min_stock > 0 and stock <= min_stock),
      'items', coalesce((
        select jsonb_agg(to_jsonb(stock_rows) order by stock_rows.stock asc)
        from (select name, stock, min_stock from public.products where min_stock > 0 and stock <= min_stock order by stock asc limit 5) as stock_rows
      ), '[]'::jsonb)
    ),
    'recentActivities', coalesce((
      select jsonb_agg(to_jsonb(activity_rows) order by activity_rows.sort_time desc)
      from (
        select * from (
          select 'log'::text as type, l.action as label, coalesce(nullif(l.details, ''), p.full_name) as details,
            l.created_at as time, l.created_at as sort_time
          from public.user_logs as l
          left join public.profiles as p on p.id = l.user_id
          union all
          select 'sms'::text as type, 'SMS ' || s.status as label, s.phone as details,
            s.created_at as time, s.created_at as sort_time
          from public.sms_messages as s
          union all
          select 'invoice'::text as type, 'Invoice ' || i.status || ' ' || i.invoice_number as label,
            coalesce(c.full_name, '') as details, i.invoice_date::timestamptz as time, i.invoice_date::timestamptz as sort_time
          from public.invoices as i
          left join public.clients as c on c.id = i.client_id
        ) as events
        order by sort_time desc
        limit 15
      ) as activity_rows
    ), '[]'::jsonb),
    'period', p_period
  ) into v_result;

  return v_result;
end;
$$;

