create or replace function public.create_invoice(
  p_client_id bigint,
  p_client_name text,
  p_invoice_date date,
  p_due_date date,
  p_tax numeric,
  p_notes text,
  p_items jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_client_id bigint := p_client_id;
  v_invoice_id bigint;
  v_invoice_number text;
  v_subtotal numeric(10, 2) := 0;
  v_item jsonb;
  v_name text;
  v_quantity integer;
  v_price numeric(10, 2);
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Invoice items must be an array' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) = 0 then
    raise exception 'At least one invoice item is required' using errcode = '22023';
  end if;
  if coalesce(p_tax, 0) < 0 then
    raise exception 'Tax cannot be negative' using errcode = '22023';
  end if;

  if v_client_id is null then
    if nullif(btrim(p_client_name), '') is null then
      raise exception 'A client is required' using errcode = '22023';
    end if;
    select id into v_client_id from public.clients
    where lower(full_name) = lower(btrim(p_client_name))
    order by id limit 1;
    if v_client_id is null then
      insert into public.clients (full_name) values (btrim(p_client_name)) returning id into v_client_id;
    end if;
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_name := nullif(btrim(v_item ->> 'name'), '');
    v_quantity := (v_item ->> 'qty')::integer;
    v_price := (v_item ->> 'price')::numeric(10, 2);
    if v_name is null or v_quantity is null or v_quantity <= 0 or v_price is null or v_price < 0 then
      raise exception 'Invoice item name, positive quantity, and nonnegative price are required' using errcode = '22023';
    end if;
    v_subtotal := v_subtotal + (v_quantity * v_price);
  end loop;

  v_invoice_id := nextval(pg_get_serial_sequence('public.invoices', 'id'));
  v_invoice_number := 'INV-' || to_char(coalesce(p_invoice_date, current_date), 'YYYYMMDD') || '-' || lpad(v_invoice_id::text, 4, '0');

  insert into public.invoices (
    id, invoice_number, client_id, invoice_date, due_date, subtotal, tax, total, notes, status
  ) values (
    v_invoice_id, v_invoice_number, v_client_id, coalesce(p_invoice_date, current_date),
    p_due_date, v_subtotal, coalesce(p_tax, 0), v_subtotal + coalesce(p_tax, 0), p_notes, 'unpaid'
  );

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_name := btrim(v_item ->> 'name');
    v_quantity := (v_item ->> 'qty')::integer;
    v_price := (v_item ->> 'price')::numeric(10, 2);
    insert into public.invoice_items (invoice_id, item_name, quantity, price, total)
    values (v_invoice_id, v_name, v_quantity, v_price, v_quantity * v_price);

    update public.products
    set stock = greatest(stock - v_quantity, 0)
    where lower(name) = lower(v_name);
  end loop;

  insert into public.user_logs (user_id, action, details)
  values ((select auth.uid()), 'invoice_create', v_invoice_number);

  return v_invoice_id;
end;
$$;

create or replace function public.record_invoice_payment(
  p_invoice_id bigint,
  p_amount numeric,
  p_payment_method text,
  p_description text,
  p_date date
)
returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_client_id bigint;
  v_transaction_id bigint;
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_amount is null or p_amount <= 0 then
    raise exception 'Payment amount must be greater than zero' using errcode = '22023';
  end if;
  if p_payment_method is not null and p_payment_method not in ('cash', 'mobile', 'card') then
    raise exception 'Unsupported payment method' using errcode = '22023';
  end if;

  select client_id into v_client_id from public.invoices where id = p_invoice_id for update;
  if not found or v_client_id is null then
    raise exception 'Invoice not found or has no client' using errcode = '22023';
  end if;

  insert into public.transactions (client_id, amount, type, payment_method, description, date, invoice_id)
  values (v_client_id, p_amount, 'payment', p_payment_method, p_description, coalesce(p_date, current_date), p_invoice_id)
  returning id into v_transaction_id;

  insert into public.user_logs (user_id, action, details)
  values ((select auth.uid()), 'invoice_payment', p_invoice_id::text || '|' || p_amount::text);

  return v_transaction_id;
end;
$$;

create or replace function public.get_dashboard(p_period text default 'month')
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_start date;
  v_end date := current_date;
  v_income numeric(14, 2);
  v_expense numeric(14, 2);
  v_week_income numeric(14, 2);
  v_week_expense numeric(14, 2);
  v_week_count bigint;
  v_chart_labels jsonb;
