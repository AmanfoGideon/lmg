create or replace function public.validate_transaction_invoice_link()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_invoice_client_id bigint;
begin
  if new.invoice_id is null then
    return new;
  end if;
  if new.type <> 'payment' then
    raise exception 'Only payment transactions may be linked to an invoice' using errcode = '22023';
  end if;

  select client_id into v_invoice_client_id
  from public.invoices
  where id = new.invoice_id;
  if not found or v_invoice_client_id is distinct from new.client_id then
    raise exception 'Payment client must match the invoice client' using errcode = '22023';
  end if;
  return new;
end;
$$;

revoke all on function public.validate_transaction_invoice_link() from public, anon, authenticated;

create trigger transactions_validate_invoice_link
  before insert or update of client_id, invoice_id, type on public.transactions
  for each row execute function public.validate_transaction_invoice_link();

