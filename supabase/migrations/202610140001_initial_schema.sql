create or replace function public.search_clients(p_query text default '', p_limit integer default 25, p_offset integer default 0)
returns table (
  id bigint,
  full_name text,
  phone text,
  email text,
  address text,
  created_at timestamptz,
  total_count bigint
)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;
  if p_limit < 1 or p_limit > 100 or p_offset < 0 then
    raise exception 'Invalid pagination values' using errcode = '22023';
  end if;

  return query
  select c.id, c.full_name, c.phone, c.email, c.address, c.created_at,
         count(*) over () as total_count
  from public.clients as c
  where coalesce(p_query, '') = ''
     or c.full_name ilike '%' || p_query || '%'
     or coalesce(c.phone, '') ilike '%' || p_query || '%'
     or coalesce(c.email, '') ilike '%' || p_query || '%'
     or coalesce(c.address, '') ilike '%' || p_query || '%'
  order by c.full_name asc, c.id asc
  limit p_limit offset p_offset;
end;
$$;

