-- Offline Sync Support Migration
-- Adds idempotency tables and functions for safe offline synchronization

-- Create idempotency tracking table for transactions
create table if not exists public.sync_idempotency (
  id bigint generated by default as identity primary key,
  idempotency_key text not null unique,
  table_name text not null,
  operation text not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  result_record_id bigint,
  created_at timestamptz not null default now(),
  processed_at timestamptz
);

create index if not exists sync_idempotency_key_idx on public.sync_idempotency (idempotency_key);
create index if not exists sync_idempotency_user_idx on public.sync_idempotency (user_id);
create index if not exists sync_idempotency_created_idx on public.sync_idempotency (created_at desc);

-- RLS for idempotency table
alter table public.sync_idempotency enable row level security;

create policy sync_idempotency_insert_own on public.sync_idempotency
  for insert to authenticated
  with check (user_id = auth.uid());

create policy sync_idempotency_read_own on public.sync_idempotency
  for select to authenticated
  using (user_id = auth.uid());

-- Add version tracking columns to main tables (for conflict detection)
alter table public.clients add column if not exists _version integer not null default 1;
alter table public.products add column if not exists _version integer not null default 1;
alter table public.transactions add column if not exists _version integer not null default 1;
alter table public.invoices add column if not exists _version integer not null default 1;

-- Create triggers to increment version on update
create or replace function public.increment_version()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new._version = old._version + 1;
  return new;
end;
$$;

create trigger clients_increment_version
  before update on public.clients
  for each row execute function public.increment_version();

create trigger products_increment_version
  before update on public.products
  for each row execute function public.increment_version();

create trigger transactions_increment_version
  before update on public.transactions
  for each row execute function public.increment_version();

create trigger invoices_increment_version
  before update on public.invoices
  for each row execute function public.increment_version();

-- Idempotent transaction creation function
create or replace function public.create_transaction_offline(
  p_idempotency_key text,
  p_client_id bigint,
  p_client_name text,
  p_amount numeric,
  p_type text,
  p_payment_method text,
  p_description text,
  p_date date,
  p_invoice_id bigint default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_existing_id bigint;
  v_result jsonb;
  v_user_id uuid := auth.uid();
begin
  if not public.is_active_member() then
    raise exception 'An active authenticated account is required' using errcode = '42501';
  end if;

  -- Check for existing idempotency key
  select result_record_id into v_existing_id
  from public.sync_idempotency
  where idempotency_key = p_idempotency_key
    and user_id = v_user_id
    and table_name = 'transactions'
    and operation = 'create'
    and processed_at is not null;

  if v_existing_id is not null then
    -- Return existing transaction
    select jsonb_build_object(
      'id', id,
      'client_id', client_id,
      'amount', amount,
      'type', type,
      'payment_method', payment_method,
      'description', description,
      'date', date,
      'invoice_id', invoice_id,
      'created_at', created_at,
      '_version', _version,
      'status', 'already_exists'
    ) into v_result
    from public.transactions
    where id = v_existing_id;

    return v_result;
  end if;

  -- Insert idempotency record
  insert into public.sync_idempotency (idempotency_key, table_name, operation, user_id)
  values (p_idempotency_key, 'transactions', 'create', v_user_id);

  -- Create transaction using existing function
  v_result := jsonb_build_object(
    'id', public.create_transaction(
      p_client_id, p_client_name, p_amount, p_type,
      p_payment_method, p_description, p_date, p_invoice_id
    ),
    'status', 'created'
  );

  -- Update idempotency record with result
  update public.sync_idempotency
  set result_record_id = (v_result ->> 'id')::bigint,
      processed_at = now()
  where idempotency_key = p_idempotency_key and user_id = v_user_id;

  return v_result;
end;
$$;

revoke all on function public.create_transaction_offline from public, anon;
grant execute on function public.create_transaction_offline to authenticated;

