-- Function to get sync metadata (last sync time, etc.)
create or replace function public.get_sync_metadata(p_user_id uuid default null)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := coalesce(p_user_id, auth.uid());
  v_last_sync timestamptz;
  v_pending_count bigint;
begin
  select max(processed_at) into v_last_sync
  from public.sync_idempotency
  where user_id = v_user_id and processed_at is not null;

  select count(*) into v_pending_count
  from public.sync_idempotency
  where user_id = v_user_id and processed_at is null;

  return jsonb_build_object(
    'last_sync', v_last_sync,
    'pending_operations', v_pending_count
  );
end;
$$;

revoke all on function public.get_sync_metadata from public, anon;
grant execute on function public.get_sync_metadata to authenticated;
