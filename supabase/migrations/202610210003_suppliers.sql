-- Function to recalculate supplier bill status
create or replace function public.recalculate_supplier_bill_status(p_bill_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_total numeric(10, 2);
  v_allocated numeric(10, 2);
  v_status text;
  v_due_date date;
begin
  select total, due_date into v_total, v_due_date
  from public.supplier_bills
  where id = p_bill_id
  for update;

  if not found then
    return;
  end if;

  select coalesce(sum(amount), 0) into v_allocated
  from public.supplier_payment_allocations
  where bill_id = p_bill_id;

  if v_allocated >= v_total then
    v_status := 'paid';
  elsif v_allocated > 0 then
    v_status := 'partial';
  else
    v_status := 'unpaid';
  end if;

  -- Check if overdue
  if v_status in ('unpaid', 'partial') and v_due_date is not null and v_due_date < current_date then
    v_status := 'overdue';
  end if;

  update public.supplier_bills
  set status = v_status
  where id = p_bill_id;
end;
$$;

revoke all on function public.recalculate_supplier_bill_status(bigint) from public, anon, authenticated;

-- Trigger to sync bill status after allocation changes
create or replace function public.sync_supplier_bill_status()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'DELETE' then
    perform public.recalculate_supplier_bill_status(old.bill_id);
    return null;
  elsif tg_op = 'INSERT' then
    perform public.recalculate_supplier_bill_status(new.bill_id);
    return null;
  elsif tg_op = 'UPDATE' then
    if old.bill_id is distinct from new.bill_id then
      perform public.recalculate_supplier_bill_status(old.bill_id);
    end if;
    perform public.recalculate_supplier_bill_status(new.bill_id);
    return null;
  end if;
  return null;
end;
$$;

revoke all on function public.sync_supplier_bill_status() from public, anon, authenticated;

create trigger supplier_payment_allocations_sync_bill_status
  after insert or update or delete on public.supplier_payment_allocations
  for each row execute function public.sync_supplier_bill_status();

-- Function to get supplier outstanding balance
create or replace function public.get_supplier_outstanding_balance(p_supplier_id bigint)
returns numeric(10, 2)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_outstanding numeric(10, 2);
begin
  select coalesce(sum(total - coalesce(
    (select coalesce(sum(amount), 0)
     from public.supplier_payment_allocations
     where bill_id = sb.id), 0)), 0)
  into v_outstanding
  from public.supplier_bills sb
  where sb.supplier_id = p_supplier_id
    and sb.status in ('unpaid', 'partial', 'overdue');

  return v_outstanding;
end;
$$;

revoke all on function public.get_supplier_outstanding_balance(bigint) from public, anon;
grant execute on function public.get_supplier_outstanding_balance(bigint) to authenticated;
