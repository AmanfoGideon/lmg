-- =======================================
-- SUPPLIER MANAGEMENT AND ACCOUNTS PAYABLE
-- =======================================

-- =======================================
-- 1) SUPPLIERS TABLE
-- =======================================
create table public.suppliers (
  id bigint generated by default as identity primary key,
  business_name text not null,
  contact_person text,
  phone text,
  email text,
  address text,
  category text,
  tax_id text,
  notes text,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null
);

create index suppliers_business_name_idx on public.suppliers (business_name);
create index suppliers_status_idx on public.suppliers (status);
create index suppliers_category_idx on public.suppliers (category);

-- =======================================
-- 2) LINK SUPPLIERS TO TRANSACTIONS
-- =======================================
alter table public.transactions
  add column if not exists supplier_id bigint references public.suppliers (id) on delete set null;

create index if not exists transactions_supplier_id_idx
  on public.transactions (supplier_id);

-- =======================================
-- 3) SUPPLIER BILLS TABLE
-- =======================================
create table public.supplier_bills (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers (id) on delete restrict,
  bill_number text not null,
  bill_date date not null,
  due_date date,
  description text,
  category text,
  subtotal numeric(10, 2) not null default 0 check (subtotal >= 0),
  tax numeric(10, 2) not null default 0 check (tax >= 0),
  total numeric(10, 2) not null check (total >= 0),
  payment_terms text,
  status text not null default 'unpaid' check (status in ('unpaid', 'partial', 'paid', 'overdue', 'cancelled')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  unique (supplier_id, bill_number)
);

create index supplier_bills_supplier_id_idx on public.supplier_bills (supplier_id);
create index supplier_bills_status_idx on public.supplier_bills (status);
create index supplier_bills_date_idx on public.supplier_bills (bill_date);
create index supplier_bills_due_date_idx on public.supplier_bills (due_date);

-- =======================================
-- 4) SUPPLIER PAYMENTS TABLE
-- =======================================
create table public.supplier_payments (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers (id) on delete restrict,
  payment_number text not null,
  payment_date date not null,
  amount numeric(10, 2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('cash', 'mobile', 'card', 'bank_transfer', 'cheque')),
  reference_number text,
  description text,
  notes text,
  status text not null default 'unallocated' check (status in ('pending', 'allocated', 'unallocated', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  unique (supplier_id, payment_number)
);

create index supplier_payments_supplier_id_idx on public.supplier_payments (supplier_id);
create index supplier_payments_status_idx on public.supplier_payments (status);
create index supplier_payments_date_idx on public.supplier_payments (payment_date);

-- =======================================
-- 5) SUPPLIER PAYMENT ALLOCATIONS TABLE
-- =======================================
create table public.supplier_payment_allocations (
  id bigint generated by default as identity primary key,
  payment_id bigint not null references public.supplier_payments (id) on delete cascade,
  bill_id bigint not null references public.supplier_bills (id) on delete restrict,
  amount numeric(10, 2) not null check (amount > 0),
  allocated_at timestamptz not null default now(),
  allocated_by uuid references public.profiles (id) on delete set null,
  unique (payment_id, bill_id)
);

create index payment_allocations_payment_id_idx on public.supplier_payment_allocations (payment_id);
create index payment_allocations_bill_id_idx on public.supplier_payment_allocations (bill_id);

