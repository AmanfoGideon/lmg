-- Function to generate supplier bill number
create or replace function public.generate_supplier_bill_number(p_supplier_id bigint)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_count integer;
  v_number text;
begin
  select count(*) into v_count
  from public.supplier_bills
  where supplier_id = p_supplier_id
    and bill_number like 'BILL-' || to_char(current_date, 'YYYYMM') || '%';

  v_number := 'BILL-' || to_char(current_date, 'YYYYMM') || '-' || lpad((v_count + 1)::text, 4, '0');
  return v_number;
end;
$$;

revoke all on function public.generate_supplier_bill_number(bigint) from public, anon;
grant execute on function public.generate_supplier_bill_number(bigint) to authenticated;

